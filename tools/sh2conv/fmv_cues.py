"""Extract Director's Cut FMV frame ranges for the port's subtitle player."""
import argparse
import struct
from pathlib import Path

from pcexe import Exe

# Movie call sites pass the first message index and a pointer to 16-bit
# start/end frames (exclusive start, inclusive end). The message bank is the caller's stage.
MOVIES = (
    ('hakaba', 4, 5, 0x8EA2C0),
    ('knife', 10, 12, 0x8E3394),
    ('hei', 14, 13, 0x8E0AC4),
    ('deai', 14, 23, 0x8E0B74),
    ('saikai', 26, 7, 0x8D81B8),
    ('korosu_a', 31, 13, 0x8D6250),
    ('korosu_b', 31, 25, 0x8D6288),
    ('rouya', 34, 13, 0x8D4240),
    ('murder', 42, 5, 0x8CBF58),
)


def cues(exe, table):
    result = []
    for i in range(128):
        start, end = struct.unpack('<HH', exe.read(table + i * 4, 4))
        if start == end == 0xFFFF:
            return result
        if start >= end or (result and start < result[-1][1]):
            raise ValueError(f'Invalid subtitle timing at {table + i * 4:#x}')
        result.append((start, end))
    raise ValueError(f'Unterminated subtitle timing table at {table:#x}')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('exe', type=Path)
    parser.add_argument('out', type=Path)
    args = parser.parse_args()
    exe = Exe(str(args.exe))
    lines = ['// Generated by tools/sh2conv/fmv_cues.py from Director\'s Cut.']
    movies = []
    for name, stage, first, address in MOVIES:
        intervals = cues(exe, address)
        assert intervals
        lines.append(f'static const MovieCue cue_{name}[] = {{')
        lines.extend(f'    {{ {start}, {end} }},' for start, end in intervals)
        lines.append('};')
        movies.append(f'    {{ "{name}", {stage}, {first}, cue_{name}, {len(intervals)} }},')
    lines += ['static const MovieSubtitles movie_subtitles[] = {', *movies, '};', '']
    args.out.write_text('\n'.join(lines))


if __name__ == '__main__':
    main()
